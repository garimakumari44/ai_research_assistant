from __future__ import annotations

from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field


class EvaluationSample(BaseModel):
    """
    Represents one RAG evaluation example.

    Contains:
    - User question
    - Retrieved documents
    - Generated answer
    - Ground truth information
    """

    question: str = Field(
        ...,
        description="User query used for evaluation",
    )

    retrieved_documents: List[str] = Field(
        default_factory=list,
        description="Documents returned by retrieval system",
    )

    generated_answer: str = Field(
        ...,
        description="Answer generated by LLM",
    )

    expected_answer: Optional[str] = Field(
        default=None,
        description="Reference answer if available",
    )

    relevant_documents: List[str] = Field(
        default_factory=list,
        description="Ground truth relevant documents",
    )

    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional evaluation metadata",
    )



class RetrievalScore(BaseModel):
    """
    Retrieval quality metrics.
    """

    recall_at_k: float = Field(
        default=0.0,
        description="Percentage of relevant documents retrieved",
    )

    precision_at_k: float = Field(
        default=0.0,
        description="Percentage of retrieved documents that are relevant",
    )

    mrr: float = Field(
        default=0.0,
        description="Mean Reciprocal Rank score",
    )

    ndcg: float = Field(
        default=0.0,
        description="Normalized Discounted Cumulative Gain",
    )



class GenerationScore(BaseModel):
    """
    LLM generation quality metrics.
    """

    faithfulness: float = Field(
        default=0.0,
        description="How grounded the answer is in retrieved context",
    )

    answer_relevance: float = Field(
        default=0.0,
        description="How relevant the answer is to the question",
    )

    context_precision: float = Field(
        default=0.0,
        description="Quality of retrieved context",
    )

    context_recall: float = Field(
        default=0.0,
        description="Coverage of required information",
    )



class PerformanceScore(BaseModel):
    """
    System performance metrics.
    """

    latency_ms: float = Field(
        default=0.0,
        description="Total response latency in milliseconds",
    )

    retrieval_latency_ms: float = Field(
        default=0.0,
        description="Retriever execution time",
    )

    generation_latency_ms: float = Field(
        default=0.0,
        description="LLM generation time",
    )

    token_usage: Optional[int] = Field(
        default=None,
        description="Total tokens consumed",
    )



class EvaluationResult(BaseModel):
    """
    Complete evaluation report.

    Combines:
    - Retrieval quality
    - Generation quality
    - Performance metrics
    """

    sample_id: Optional[str] = None

    retrieval: RetrievalScore

    generation: GenerationScore

    performance: PerformanceScore

    metadata: Dict[str, Any] = Field(
        default_factory=dict,
    )