/* -------------------------------------------------------------------------- */
/* Utility helpers                                                             */
/* -------------------------------------------------------------------------- */

/**
 * Determine whether a strategy supports graph augmentation.
 */
export function isGraphAugmentedStrategy(
  strategy: AdaptiveRAGStrategyValue,
): boolean {
  return strategy === "graph_augmented";
}

/**
 * Determine whether a strategy can perform iterative retrieval.
 */
export function supportsAdaptiveRAGIteration(
  strategy: AdaptiveRAGStrategyValue,
): boolean {
  return (
    strategy === "iterative" ||
    strategy === "graph_augmented"
  );
}

/**
 * Determine whether a strategy supports query expansion.
 */
export function supportsAdaptiveRAGQueryExpansion(
  strategy: AdaptiveRAGStrategyValue,
): boolean {
  return (
    strategy === "multi_query" ||
    strategy === "corrective" ||
    strategy === "graph_augmented"
  );
}

/**
 * Determine whether a strategy supports corrective retrieval.
 */
export function supportsAdaptiveRAGCorrection(
  strategy: AdaptiveRAGStrategyValue,
): boolean {
  return (
    strategy === "corrective" ||
    strategy === "graph_augmented"
  );
}

/**
 * Determine whether the current execution is still running.
 */
export function isAdaptiveRAGRunning(
  status: AdaptiveRAGStatus,
): boolean {
  return (
    status === "pending" ||
    status === "analyzing" ||
    status === "planning" ||
    status === "retrieving" ||
    status === "expanding" ||
    status === "reranking" ||
    status === "collecting_evidence"
  );
}

/**
 * Determine whether the execution has reached a terminal state.
 */
export function isAdaptiveRAGTerminal(
  status: AdaptiveRAGStatus,
): boolean {
  return (
    status === "completed" ||
    status === "failed" ||
    status === "cancelled"
  );
}