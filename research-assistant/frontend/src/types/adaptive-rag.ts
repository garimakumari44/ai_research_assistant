/**
 * Canonical Adaptive RAG response.
 *
 * This is the top-level object consumed by the frontend.
 *
 * Conceptually:
 *
 * AdaptiveRAGResponse
 * │
 * ├── query
 * ├── strategy
 * ├── strategy_selection
 * ├── query_analysis
 * ├── query_expansion
 * ├── graph_augmentation
 * ├── retrieval
 * ├── iterations
 * ├── correction
 * ├── quality
 * └── results
 */
export interface AdaptiveRAGResponse {
  /**
   * Unique execution identifier.
   */
  execution_id: AdaptiveRAGId;

  /**
   * Original query.
   */
  query: string;

  /**
   * Strategy selected for the execution.
   */
  strategy: AdaptiveRAGStrategyValue;

  /**
   * Strategy selection details.
   */
  strategy_selection?: AdaptiveRAGStrategySelection | null;

  /**
   * Overall execution status.
   */
  status: AdaptiveRAGStatus;

  /**
   * Query analysis.
   */
  query_analysis?: AdaptiveRAGQueryAnalysis | null;

  /**
   * Query expansion generated by multi-query/corrective strategies.
   */
  query_expansion?: AdaptiveRAGQueryExpansion | null;

  /**
   * Graph augmentation information.
   *
   * Present when graph_augmented is selected or when the
   * planner activates graph retrieval for another strategy.
   */
  graph_augmentation?: AdaptiveRAGGraphAugmentation | null;

  /**
   * Retrieval execution summary.
   */
  retrieval?: AdaptiveRAGRetrievalSummary | null;

  /**
   * Iteration history.
   */
  iterations?: AdaptiveRAGIteration[];

  /**
   * Corrective retrieval information.
   */
  correction?: AdaptiveRAGCorrection | null;

  /**
   * Final quality assessment.
   */
  quality?: AdaptiveRAGQualityAssessment | null;

  /**
   * Retrieval results.
   *
   * The canonical result shape is defined in `retrieval.ts`.
   *
   * Kept as `unknown[]` here to avoid duplicating the retrieval
   * contract and creating circular type dependencies.
   *
   * The API layer should map these to `RetrievalResult[]`.
   */
  results: unknown[];

  /**
   * Number of final results.
   */
  total: number;

  /**
   * Execution steps.
   */
  steps?: AdaptiveRAGStep[];

  /**
   * Total execution time in milliseconds.
   */
  execution_time_ms?: number | null;

  /**
   * Backend diagnostics.
   */
  metadata: AdaptiveRAGMetadata;

  /**
   * Error information when execution fails.
   */
  error?: string | null;

  /**
   * Creation timestamp.
   */
  created_at?: string | null;

  /**
   * Completion timestamp.
   */
  completed_at?: string | null;
}

