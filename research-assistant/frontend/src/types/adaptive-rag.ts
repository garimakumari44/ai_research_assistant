/**
 * Frontend types for the Adaptive RAG system.
 *
 * The Adaptive RAG layer is responsible for selecting and executing
 * the most appropriate retrieval strategy for a research query.
 *
 * Supported strategies:
 *
 *   direct
 *   iterative
 *   corrective
 *   multi_query
 *   graph_augmented
 *
 * The graph_augmented strategy does NOT represent a separate Graph RAG
 * API. It is an adaptive retrieval strategy that can combine:
 *
 *   query analysis
 *        ↓
 *   semantic retrieval
 *        ↓
 *   keyword retrieval
 *        ↓
 *   graph expansion
 *        ↓
 *   evidence collection
 *        ↓
 *   reranking
 */
 
/* -------------------------------------------------------------------------- */
/* Shared types                                                               */
/* -------------------------------------------------------------------------- */

/**
 * Arbitrary metadata returned by the backend.
 */
export type AdaptiveRAGMetadata = Record<string, unknown>;

/**
 * UUID values are serialized as strings in JSON responses.
 */
export type AdaptiveRAGId = string;

/**
 * Execution status of an Adaptive RAG request.
 */
export type AdaptiveRAGStatus =
  | "idle"
  | "pending"
  | "analyzing"
  | "planning"
  | "retrieving"
  | "expanding"
  | "reranking"
  | "collecting_evidence"
  | "completed"
  | "failed"
  | "cancelled";

/**
 * Supported Adaptive RAG strategies.
 *
 * These values should remain aligned with the backend strategy
 * implementation.
 */
export type AdaptiveRAGStrategy =
  | "direct"
  | "iterative"
  | "corrective"
  | "multi_query"
  | "graph_augmented";

/**
 * Strategy aliases used by older frontend/backend integrations.
 *
 * Keep this extensible so the frontend can tolerate future strategies.
 */
export type AdaptiveRAGStrategyValue =
  | AdaptiveRAGStrategy
  | string;

/**
 * Retrieval capabilities that Adaptive RAG may activate.
 */
export type AdaptiveRAGRetrievalMethod =
  | "semantic"
  | "keyword"
  | "graph"
  | "hybrid"
  | "unknown"
  | string;

