  /**
   * Query classification information.
   */
  query_type?: string | null;

  /**
   * Research intent.
   */
  intent?: string | null;

  /**
   * Domain identified by the planner.
   */
  domain?: string | null;

  /**
   * Optional filters inferred from the query.
   */
