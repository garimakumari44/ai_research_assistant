/**
 * Query submitted to the Adaptive RAG planner.
 */
export interface AdaptiveRAGQuery {
  /**
   * Original natural-language research query.
   */
  query: string;

  /**
   * Optional paper restriction.
   */
  paper_id?: AdaptiveRAGId | null;

  /**
   * Optional document restriction.
   */
  document_id?: AdaptiveRAGId | null;

  /**
   * Maximum number of final results.
   */
  top_k?: number;

  /**
   * Optional retrieval methods explicitly requested
   * by the frontend.
   *
   * Normally the planner decides this automatically.
   */
  retrieval_methods?: AdaptiveRAGRetrievalMethod[];

  /**
   * Enable graph expansion when supported by the strategy.
   */
  graph_enabled?: boolean;

  /**
   * Maximum graph traversal depth.
   */
  graph_depth?: number;

  /**
   * Maximum number of graph-derived candidates.
   */
  graph_top_k?: number;

  /**
   * Optional filters passed to the retrieval layer.
   */
  filters?: AdaptiveRAGMetadata;

  /**
   * Optional client metadata.
   */
  metadata?: AdaptiveRAGMetadata;
}

